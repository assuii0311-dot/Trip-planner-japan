/**
 * 그 나라의 지도 범위. 등록된 것이 없으면 도시들로 만들어 낸다 —
 * 새 나라를 붙일 때 범위를 적기 전이라도 지도가 나와야 한다.
 */
export function frameOf(country: string, pts: { lat: number; lon: number }[] = []): MapFrame {
  const f = FRAMES[country];
  if (f) return f;
  if (!pts.length) return { lon: [-180, 180], lat: [-60, 75] };
  const lons = pts.map((p) => p.lon);
  const lats = pts.map((p) => p.lat);
  const pad = 1.2;
  return {
    lon: [Math.min(...lons) - pad, Math.max(...lons) + pad],
    lat: [Math.min(...lats) - pad, Math.max(...lats) + pad],
  };
}
