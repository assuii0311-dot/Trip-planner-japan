/**
 * 지도에 그릴 범위와 '본토 밖' 경계.
 *
 * 축척을 여행마다 바꾸면 계획끼리 비교가 안 되므로 나라마다 고정한다.
 * `farLon` 보다 서쪽(또는 `farLat` 보다 남쪽)에 있는 도시는 본토 지도에
 * 넣지 않고 따로 적는다 — 스페인은 카나리아 제도가 아프리카 서쪽에 있어
 * 함께 그리면 본토가 우표만 해진다.
 */
export interface MapFrame {
  lon: [number, number];
  lat: [number, number];
  /** 이 경도보다 서쪽은 본토 지도에 넣지 않는다. */
  farLon?: number;
  /** 본토 밖 도시를 뭐라고 부를지. */
  farLabel?: string;
}

