  spain: { lon: [-9.6, 4.5], lat: [35.6, 44.2], farLon: -12, farLabel: '카나리아 제도' },
  // 지금은 도쿄와 근교뿐이다. 전국 범위로 그리면 도쿄와 하코네가 한 점이 된다.
  japan: { lon: [138.0, 141.2], lat: [34.8, 37.2] },
